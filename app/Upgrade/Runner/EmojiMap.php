    public static function convert(string $text): string
    {
        return preg_replace_callback(
            '/\[([ies]):([0-9]{1,3})\]/',
            static fn (array $m): string => self::TABLE[$m[1]][(int) $m[2]] ?? $m[0],
            $text,
        );
    }
